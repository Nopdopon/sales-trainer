def screen_review():
    persona = get_persona()
    if not persona:
        st.session_state.screen = "menu"
        st.rerun()
        return

    st.markdown(f"""
    <div style="display:flex;align-items:center;gap:12px;margin-bottom:8px;">
        <div style="font-size:32px;">🧑‍⚖️</div>
        <div>
            <div style="font-size:22px;font-weight:800;color:#e8e8ff;">Разбор полётов</div>
            <div style="font-size:13px;color:#505070;">Переговоры с {persona.emoji} {persona.name} · {persona.topic} · {persona.call_type} звонок</div>
        </div>
    </div>
    """, unsafe_allow_html=True)

    if st.session_state.auto_ended:
        reason = "клиент достиг максимального уровня стресса" if st.session_state.stress >= 100 else "слишком много слабых ответов подряд"
        st.warning(f"⚠️ Диалог был автоматически завершён клиентом ({reason}).")

    manager_turns = [m for m in st.session_state.messages if m["role"] == "manager"]
    if not st.session_state.messages or len(manager_turns) == 0:
        st.warning("Диалог слишком короткий для анализа. Вернитесь и напишите хотя бы пару сообщений.")
        if st.button("← Вернуться к диалогу", key="back_short_dialog"):
            st.session_state.screen = "chat" if st.session_state.mode == "chat" else "call"
            st.session_state.deal_closed = False
            st.session_state.auto_ended = False
            st.session_state.review_result = None
            st.session_state.review_error = None
            st.rerun()
        return

    if not _get_sber_key() or not GIGACHAT_AVAILABLE:
        st.error("SBER_AUTH_KEY не настроен (или пакет `gigachat` не установлен) — оценка недоступна.")
        if st.button("← Вернуться к диалогу", key="back_no_api"):
            st.session_state.screen = "chat" if st.session_state.mode == "chat" else "call"
            st.session_state.deal_closed = False
            st.rerun()
        return

    if st.session_state.review_result is None and st.session_state.review_error is None:
        with st.spinner("ИИ-судья анализирует переговоры..."):
            try:
                st.session_state.review_result = run_ai_judge(persona)
            except AIClientError as e:
                st.session_state.review_error = str(e)
            except Exception as e:
                # Ловим любые непредвиденные исключения — приложение не должно крашиться
                st.session_state.review_error = f"Неожиданная ошибка: {type(e).__name__}: {e}"

    if st.session_state.review_error:
        err_text = st.session_state.review_error

        if "404" in err_text or "not found" in err_text.lower():
            st.error(
                f"❌ **Модель `{GIGACHAT_MODEL}` не найдена (ошибка 404)**\n\n"
                f"Проверьте константу `GIGACHAT_MODEL` в начале `app.py` и доступность модели в вашем тарифе GigaChat.\n\n"
                f"Детали: `{err_text}`"
            )
        elif "quota" in err_text.lower() or "429" in err_text:
            st.error(
                f"❌ **Превышена квота GigaChat API (429 Too Many Requests)**\n\n"
                f"Подождите несколько минут и нажмите «Повторить попытку».\n\n"
                f"Детали: `{err_text}`"
            )
        else:
            st.error(f"❌ Не удалось получить оценку от ИИ-судьи:\n\n`{err_text}`")

        col_retry, col_back = st.columns(2)
        with col_retry:
            if st.button("🔁 Повторить попытку", use_container_width=True, type="primary"):
                st.session_state.review_error = None
                st.rerun()
        with col_back:
            if st.button("← Вернуться к диалогу", use_container_width=True, key="back_api_error"):
                st.session_state.screen = "chat" if st.session_state.mode == "chat" else "call"
                st.session_state.deal_closed = False
                st.session_state.review_result = None
                st.session_state.review_error = None
                st.rerun()
        return

    result = st.session_state.review_result

    if result.get("_partial"):
        st.warning("⚠️ Ответ модели был обрезан (превышен лимит токенов), часть полей могла не сохраниться.")
        if st.button("🔁 Пересчитать оценку заново", key="recompute_partial"):
            st.session_state.review_result = None
            st.session_state.review_error = None
            st.rerun()

    render_review_body(result)

    st.markdown("<div style='height:16px'></div>", unsafe_allow_html=True)
    st.divider()

    # ── Автосохранение: в базу (история аккаунта) или, если база не подключена, в CSV ──
    if "_saved_status" not in result:
        if db_enabled():
            ok, db_err = save_session_to_db(persona, result)
            if ok:
                result["_saved_status"] = ("ok", "💾 Тренировка сохранена в вашу историю — раздел «📚 Моя история» в боковом меню.")
            else:
                save_to_csv(persona, result)   # резервная копия, чтобы результат не потерялся
                result["_saved_status"] = ("warn", f"⚠️ Не удалось сохранить в базу ({db_err}). Копия записана во временный файл.")
        else:
            saved = save_to_csv(persona, result)
            result["_saved_status"] = (
                ("ok", "💾 Результат сохранён в `kosmos_history.csv`") if saved
                else ("warn", "⚠️ Не удалось сохранить результат.")
            )
    _kind, _msg = result["_saved_status"]
    (st.success if _kind == "ok" else st.warning)(_msg)

    # Скачивание CSV — только если база не подключена
    if not db_enabled() and HISTORY_CSV.exists():
        with open(HISTORY_CSV, "rb") as f:
            st.download_button(
                label="⬇️ Скачать историю диалогов (CSV)",
                data=f.read(),
                file_name="kosmos_history.csv",
                mime="text/csv",
                use_container_width=True,
            )

    col_a, col_b = st.columns(2)
    with col_a:
        if st.button("🔁 Попробовать снова с этим клиентом", use_container_width=True):
            reset_dialog_state()
            st.session_state.stress = persona.stress_start
            st.session_state.screen = "chat" if st.session_state.mode == "chat" else "call"
            st.rerun()
    with col_b:
        if st.button("← Выбрать другого клиента", use_container_width=True, type="primary"):
            st.session_state.screen = "menu"
            st.session_state.persona_key = None
            reset_dialog_state()
            st.rerun()

    with st.expander("📜 Полный лог диалога"):
        for m in st.session_state.messages:
            who = "👤 Менеджер" if m["role"] == "manager" else f"{persona.emoji} {persona.name}"
            st.markdown(f"**{who}:** {m['text']}")


