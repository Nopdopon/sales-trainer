def save_to_csv(persona: "Persona", result: Dict) -> bool:
    """
    Записывает результат разбора полётов в kosmos_history.csv.
    Создаёт файл с заголовком если его нет. Возвращает True при успехе.
    """
    try:
        file_exists = HISTORY_CSV.exists()
        with open(HISTORY_CSV, "a", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=HISTORY_COLS)
            if not file_exists:
                writer.writeheader()

            strengths = "; ".join(result.get("strengths", []))
            mistakes_raw = result.get("mistakes", [])
            mistakes = "; ".join(
                f"{m.get('moment','')}: {m.get('issue','')}" for m in mistakes_raw
            )
            next_steps = "; ".join(result.get("next_steps", []))

            writer.writerow({
                "Дата/Время":        datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                "Логин менеджера":   st.session_state.get("current_user", "unknown"),
                "Тема звонка":       persona.topic,
                "Тип звонка":        persona.call_type,
                "Персонаж":          persona.name,
                "Оценка (1-10)":     result.get("score", "—"),
                "Сильные стороны":   strengths,
                "Ошибки":            mistakes,
                "Рекомендации тренеру": next_steps,
            })
        return True
    except Exception:
        return False


