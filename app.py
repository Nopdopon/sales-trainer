def check_auto_end(persona: Persona) -> bool:
    """Возвращает True, если разговор должен автоматически завершиться (стресс=100 или превышено терпение)."""
    if st.session_state.stress >= 100:
        return True
    if st.session_state.weak_streak >= persona.patience:
        return True
    return False


def trigger_auto_end(persona: Persona):
    """Добавляет финальную реплику клиента и переводит в режим завершённого диалога + сразу на экран review."""
    st.session_state.messages.append({
        "role": "client",
        "text": f"*{persona.name} {'повесил трубку' if st.session_state.mode == 'call' else 'прервал чат'}* — {persona.hangup_line}",
        "ts": datetime.now().strftime("%H:%M"),
    })
    st.session_state.call_active = False
    st.session_state.call_ended_reason = "auto_hangup"
    st.session_state.auto_ended = True
    st.session_state.deal_closed = True
    st.session_state.screen = "review"


def manager_send(text: str, persona: Persona) -> Optional[str]:
    """
    Отправляет реплику менеджера, запрашивает ответ ИИ-клиента с учётом полного контекста диалога,
    и проверяет условия авто-завершения. Возвращает текст ошибки (если был сбой вызова ИИ) или None.
    """
    text = text.strip()
    if not text:
        return None

    st.session_state.messages.append({
        "role": "manager", "text": text, "ts": datetime.now().strftime("%H:%M"),
    })

    # Эвристика нужна только для weak_streak (счётчик терпения по тексту менеджера).
    # Сам стресс будет перезаписан значением от ИИ, если JSON придёт корректно.
    update_stress(text)

    # Если лимит терпения уже превышен — клиент обрывает без ответа ИИ
    if check_auto_end(persona):
        trigger_auto_end(persona)
        return None

    try:
        with st.spinner(f"{persona.name} печатает..."):
            reply, ai_stress = call_ai_client(persona, st.session_state.messages)
    except AIClientError as e:
        return str(e)

    # Обновляем стресс: если ИИ вернул stress_level в JSON — используем его (приоритет).
    # Если нет (ai_stress is None, модель не вернула JSON) — оставляем эвристику как есть.
    if ai_stress is not None:
        st.session_state.stress = ai_stress
        # Пересчитываем weak_streak на основе оценки самого ИИ:
        # высокий стресс (≥75) — менеджер явно облажался, увеличиваем счётчик
        if ai_stress >= 75:
            st.session_state.weak_streak += 1
        else:
            st.session_state.weak_streak = 0

    st.session_state.messages.append({
        "role": "client", "text": reply, "ts": datetime.now().strftime("%H:%M"),
    })
    st.session_state.turn_count += 1

    # Озвучка ответа ИИ-клиента (Yandex SpeechKit)
    # Озвучка именно тем голосом Yandex, который закреплён за этим персонажем
    # ВАЖНО: звук здесь НЕ синтезируется — иначе текст ответа появился бы только после озвучки.
    # Реплика ставится в очередь и озвучивается уже ПОСЛЕ того, как страница с текстом отрисована.
    st.session_state.pending_tts = {"text": reply, "voice": persona.voice}

    # Повторная проверка авто-завершения после обновления стресса
    if check_auto_end(persona):
        trigger_auto_end(persona)

    return None


